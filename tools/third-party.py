#!/usr/bin/env python3
# Prints the third-party Rust crates linked into one of the app's builds, each with its licence and
# the licence files it ships, from `cargo metadata` and the crates' own folders. Build scripts,
# proc-macros and dev-dependencies stay out, as none of them reach the build. tools/licences.sh
# writes it into each package as THIRD-PARTY.txt; NOTICE has the rest, chrome://credits Chromium's.
# Usage: tools/third-party.py <Cargo.toml> <target triple> [cargo metadata flags...]
import hashlib
import json
import os
import re
import subprocess
import sys

manifest, target, *flags = sys.argv[1:]
app = os.path.dirname(os.path.dirname(os.path.abspath(__file__))) + os.sep + "app" + os.sep
meta = json.loads(subprocess.run(
    ["cargo", "metadata", "--format-version", "1", "--manifest-path", manifest,
     "--filter-platform", target, *flags],
    check=True, stdout=subprocess.PIPE, text=True).stdout)
packages = {p["id"]: p for p in meta["packages"]}
nodes = {n["id"]: n for n in meta["resolve"]["nodes"]}

# Ours are the path crates in app/ outside .deps/, where Zed's are.
def ours(p):
    path = p["manifest_path"]
    return p["source"] is None and path.startswith(app) and os.sep + ".deps" + os.sep not in path

linked, todo = set(), [meta["resolve"]["root"]]
while todo:
    id = todo.pop()
    if id in linked or any("proc-macro" in t["kind"] for t in packages[id]["targets"]):
        continue
    linked.add(id)
    todo += [d["pkg"] for d in nodes[id]["deps"] if any(k["kind"] is None for k in d["dep_kinds"])]

MIT = """Permission is hereby granted, free of charge, to any person obtaining a copy of this software
and associated documentation files (the "Software"), to deal in the Software without restriction,
including without limitation the rights to use, copy, modify, merge, publish, distribute,
sublicense, and/or sell copies of the Software, and to permit persons to whom the Software is
furnished to do so, subject to the following conditions:

The above copyright notice and this permission notice shall be included in all copies or
substantial portions of the Software.

THE SOFTWARE IS PROVIDED "AS IS", WITHOUT WARRANTY OF ANY KIND, EXPRESS OR IMPLIED, INCLUDING BUT
NOT LIMITED TO THE WARRANTIES OF MERCHANTABILITY, FITNESS FOR A PARTICULAR PURPOSE AND
NONINFRINGEMENT. IN NO EVENT SHALL THE AUTHORS OR COPYRIGHT HOLDERS BE LIABLE FOR ANY CLAIM,
DAMAGES OR OTHER LIABILITY, WHETHER IN AN ACTION OF CONTRACT, TORT OR OTHERWISE, ARISING FROM, OUT
OF OR IN CONNECTION WITH THE SOFTWARE OR THE USE OR OTHER DEALINGS IN THE SOFTWARE."""

LICENCE = re.compile(r"^(licen[cs]e|copying|copyright|notice|unlicense)([-_.].*)?$", re.I)

def licence_files(p):
    dir = os.path.dirname(p["manifest_path"])
    files = sorted(f for f in os.listdir(dir) if LICENCE.match(f) and os.path.isfile(os.path.join(dir, f)))
    if p["license_file"] and os.path.basename(p["license_file"]) not in files:
        files.append(p["license_file"])
    # A crate in a repository's crates/ folder, as Zed's are, may keep its licence at the top.
    while not files and p["source"] is None and os.path.basename(dir) != ".deps":
        dir = os.path.dirname(dir)
        files = sorted(f for f in os.listdir(dir) if LICENCE.match(f) and os.path.isfile(os.path.join(dir, f)))
    return [os.path.join(dir, f) for f in files]

third = sorted((packages[id] for id in linked if not ours(packages[id])), key=lambda p: (p["name"], p["version"]))
print(f"The {len(third)} Rust crates ilo's app links on {target}, with their licences, generated by")
print("tools/third-party.py. NOTICE names the other projects ilo uses; Chromium's own are in the")
print("browser, at chrome://credits.")
seen, missing = {}, []
for p in third:
    print("\n" + "=" * 100)
    print(f"{p['name']} {p['version']}, {p['license'] or 'see its licence file'}")
    if p["repository"]:
        print(p["repository"])
    files = licence_files(p)
    licence = p["license"] or ""
    if not files and "Apache-2.0" in licence:
        print("\nThe crate ships no licence file. It's used under the Apache License 2.0, whose full")
        print("text is at the end of NOTICE.")
    elif not files and re.search(r"\bMIT\b", licence):
        print("\nThe crate ships no licence file. Its licence, MIT, with the authors it names:")
        print("\nCopyright (c) " + ", ".join(p["authors"] or [p["name"] + "'s authors"]) + "\n\n" + MIT)
    elif not files:
        missing.append(p["name"])
        print("\nThe crate ships no licence file; its licence is the one named above.")
    for file in files:
        text = open(file, encoding="utf-8", errors="replace").read().strip()
        key = hashlib.sha256(" ".join(text.split()).encode()).hexdigest()
        print(f"\n{os.path.basename(file)}:")
        if key in seen:
            print(f"The same text as {seen[key]}'s, above.")
        else:
            seen[key] = f"{p['name']} {p['version']}"
            print("\n" + text)
if missing:
    print(f"third-party.py: no licence file in {', '.join(missing)}", file=sys.stderr)
